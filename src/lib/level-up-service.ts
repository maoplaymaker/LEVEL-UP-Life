export type Category =
  | "Salud"
  | "Estudio"
  | "Trabajo"
  | "Finanzas"
  | "Relaciones"
  | "Familia"
  | "Ocio"
  | "Espiritualidad";

export const CATEGORIES: Category[] = ["Salud", "Estudio", "Trabajo", "Finanzas", "Relaciones", "Familia", "Ocio", "Espiritualidad"];

export interface LifeStat {
  category: Category;
  level: number;
  xp: number;
  nextLevelXp: number;
  reflection?: string;
}
export type Difficulty = "Fácil" | "Media" | "Difícil";
export type TaskType = "daily" | "main";

export interface Player {
  id: string;
  name: string;
  handle: string;
  level: number;
  currentXp: number;
  nextLevelXp: number;
  totalPoints: number;
  streak: number;
  multiplier: number;
}

export interface LevelRank { min: number; max: number; key: string }
export const LEVEL_RANKS: LevelRank[] = [
  { min: 1, max: 4, key: "novice" }, { min: 5, max: 9, key: "explorer" },
  { min: 10, max: 19, key: "driver" }, { min: 20, max: 34, key: "elite" },
  { min: 35, max: 49, key: "master" }, { min: 50, max: 74, key: "legend" },
  { min: 75, max: 999, key: "god" },
];
export function getLevelRank(level: number) { return LEVEL_RANKS.find((rank) => level >= rank.min && level <= rank.max) ?? LEVEL_RANKS[0]; }

export interface Mission {
  id: string;
  title: string;
  category: Category;
  difficulty: Difficulty;
  xp: number;
  type: TaskType;
  completed: boolean;
  /** ISO date (YYYY-MM-DD) when the mission was completed */
  completedOn?: string;
  /** true = title comes from the translation catalog (demo data) */
  i18n?: boolean;
  /** translation key for missions generated by the spin wheel */
  titleKey?: string;
  /** ISO date (YYYY-MM-DD) deadline shown in the agenda */
  dueDate?: string;
  /** local time (HH:mm) used by the daily agenda */
  scheduledTime?: string;
  /** coaching reminder generated for this task */
  reminder?: string;
  /** check items; the server keeps them in sync with other apps */
  checklist?: { id: string; text: string; done: boolean }[];
}

