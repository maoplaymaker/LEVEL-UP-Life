const WOMEN_CHARACTERS = new Set(["char_hacker", "char_biker", "char_royal", "char_luna", "char_amara", "char_sora", "char_noor", "char_freya", "char_ruby", "char_priya"]);
export function canWearOutfit(character: string | null, outfit: string): boolean {
  if (outfit === "outfit_exec") return !WOMEN_CHARACTERS.has(character ?? "char_runner");
  if (outfit === "outfit_exec_women") return WOMEN_CHARACTERS.has(character ?? "char_runner");
  return true;
}
